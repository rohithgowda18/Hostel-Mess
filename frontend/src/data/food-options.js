export const getMealDisplayName = (mealType) => {
  const map = {
    BREAKFAST: 'Breakfast',
    LUNCH: 'Lunch',
    SNACKS: 'Evening Snacks',
    DINNER: 'Dinner'
  };
  return map[mealType] || mealType;
};

export const searchFoodCatalog = (category = 'All', searchQuery = '') => {
  let items = [];
  if (category === 'All') {
    Object.values(FOOD_CATALOG_BY_CATEGORY).forEach(list => {
      items.push(...list);
    });
  } else if (FOOD_CATALOG_BY_CATEGORY[category]) {
    items = [...FOOD_CATALOG_BY_CATEGORY[category]];
  }

  if (searchQuery && searchQuery.trim()) {
    const q = searchQuery.trim().toLowerCase();
    items = items.filter(item => item.toLowerCase().includes(q));
  }
  return Array.from(new Set(items));
};
